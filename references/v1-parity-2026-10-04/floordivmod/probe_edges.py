"""edge branches of v1 // % divmod and their v2 spelling: print both outcomes side by side"""
from common import *
import warnings as W
M1, M2 = v1.MultiInterval, v2.MultiInterval
def both(label, f1, f2):
    s1, r1 = run(f1)
    with W.catch_warnings(record=True) as w:
        W.simplefilter('always')
        s2, r2 = run(f2)
    o1 = show(v1_pieces(r1)) if s1 == 'ok' and isinstance(r1, M1) else r1
    if s2 == 'ok' and isinstance(r2, M2): o2 = show(v2_pieces(r2))
    elif s2 == 'ok' and isinstance(r2, tuple): o2 = tuple(show(v2_pieces(x)) for x in r2)
    else: o2 = r2
    ws = sorted({type(x.message).__name__ if not isinstance(x.message, str) else x.category.__name__ for x in w})
    print(f'{label:42s} | v1: {o1!s:40s} | v2: {o2} {ws if ws else ""}')

